def render_template(day: str, sign: Sign, topic: Topic, attempt: int = 1) -> str:
    variants = TOPIC_LINES[topic]
    digest = sha256(f"{day}/{sign}/{topic}".encode()).digest()
    index = (digest[0] + attempt - 1) % len(variants)
    return f"{SIGN_NAMES[sign]} · {TOPIC_NAMES[topic]}. {variants[index]} {SIGN_LINES[sign]}"
